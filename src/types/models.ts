import type { Tables } from '@/integrations/supabase/types';
export type Course = Tables<'courses'> & { profiles?: { full_name: string | null }; enrollments?: { count: number }[] };
export type Lesson = Tables<'lessons'>;
export type Module = Tables<'modules'> & { lessons: Lesson[] };
export type LiveSession = Tables<'live_classes'> & { courses?: { title: string } };
export type Assignment = Tables<'assignments'> & { courses?: { title: string; teacher_id: string } };
export type Submission = Tables<'submissions'> & { profiles?: { full_name: string } };
export type Recording = Tables<'class_recordings'> & { live_classes?: { course_id: string } };
export type Quiz = Tables<'quizzes'>;
export type Question = Omit<Tables<'quiz_questions'>, 'correct_answer'> & { correct_answer?: number };
export type Attempt = Tables<'quiz_attempts'>;
export type Discussion = Tables<'course_discussions'>;
export type Post = Tables<'community_posts'> & { profiles?: { full_name: string; avatar_url?: string } };
export type Review = Tables<'course_reviews'> & { profiles?: { full_name: string; avatar_url: string | null } };
